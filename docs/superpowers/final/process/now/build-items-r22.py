def hm(nm):
    m = re.search(r'-(\d\d)(\d\d)\.png$', nm); return f'{m.group(1)}:{m.group(2)}'


def T(shots):
    ts = sorted(hm(s) for s in shots if s and s.startswith('now-'))
    if not ts: return ''
    d = datetime.date.today()
    return f'(그림 찍은 시각 {d.month}월 {d.day}일 {ts[0]}' + ('' if ts[0] == ts[-1] else f'–{ts[-1]}') + ')'


def nb(s):
    s = re.sub(r' (?=→)|(?<=→) ', NBSP, s)
    s = re.sub(r'(?<=[가-힣A-Za-z]) (?=\d)', NBSP, s)
    s = re.sub(r'(?<=\d) (?=(?:km|㎢|㎡|ha|곳|필지|건|초|W|kg|GB|MB|KB|개|명|회|장|동|칸|줄|번|일|배|해|판|분|m|cm)|%)', NBSP, s)
    return s


