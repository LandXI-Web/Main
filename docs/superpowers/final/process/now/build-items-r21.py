def nb(s):
    """숫자와 단위 · 화살표 앞뒤 공백은 줄바꿈 때 갈라지지 않게(줄바꿈 규칙 3-9) — 줄 안 끊김 공백(NBSP)으로 바꾼다."""
    N = ' '
    s = re.sub(r' (?=→)|(?<=→) ', N, s)
    s = re.sub(r'(?<=[가-힣A-Za-z]) (?=\d)', N, s)
    s = re.sub(r'(?<=\d) (?=(?:km|㎢|㎡|ha|곳|필지|건|초|W|kg|GB|MB|KB|개|명|회|장|동|칸|줄|번|일|배|해|판)|%)', N, s)
    return s


