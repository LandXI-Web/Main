/* words.js — 서버 기록에서 온 이름(카드 이름 등)을 화면 용어표(E:/Land-XI 플랫폼/CLAUDE.md §2 · 명세 §5)로 바꿔 보인다.
   정본은 서버 기록을 고치는 것(보고서 '요청') — 그 전까지 LX 직원 화면 5종에 내부 말이 새지 않게 하는 표시용 한 곳. 새 말은 만들지 않는다. */
const MAP = [
  [/판독/g, 'AI 분석'], [/검수/g, '결과 확인'], [/반입/g, '데이터 올리기'], [/조립/g, '서비스 만들기'],
  [/이식/g, '기관에 공유'], [/발행/g, '서비스 공개'], [/생산\s?콘솔/g, 'LX 직원 대시보드'], [/관제/g, 'LX 관리자 대시보드'],
];
export const say = (s) => MAP.reduce((t, [re, w]) => t.replace(re, w), String(s ?? ''));
